def watch_clipboard(interval=0.2, callback=None):
    """阻塞式监听剪贴板变化"""
    last = pyperclip.paste()
    while True:
        time.sleep(interval)
        try:
            cur = pyperclip.paste()
        except Exception:
            continue          # 剪贴板被别的程序占用，跳过这轮
        if cur != last:
            last = cur
            if callback:
                callback(cur)
            else:
                return cur


